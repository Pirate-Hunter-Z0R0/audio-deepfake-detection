"""
voice_generation/evaluate_synthetic_dataset.py
----------------------------------------------
Evaluates our existing trained detectors (Baseline SVM and Deep ResNeXt CNN)
against newly generated synthetic RVC audio samples.

Design Principles:
    - Imports and reuses existing preprocessing and feature extraction directly from src/.
    - Does NOT modify, retrain, or rebuild any detection code.
    - Reports true, unrounded predictions and confidences for every sample.
    - Computes overall and per-speaker detection rates.
    - Saves detailed evaluation output to results/rvc_synthetic_evaluation.csv.
"""

import os
import sys
import argparse
from pathlib import Path
from typing import Dict, List, Any, Optional

import numpy as np
import pandas as pd
import joblib

# Add project root to sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.test_cloned_samples import preprocess_and_extract


def evaluate_synthetic_dataset(
    audio_dir: str = "data/synthetic_rvc",
    metadata_file: str = "data/synthetic_rvc/metadata.csv",
    scaler_path: str = "models/scaler.pkl",
    baseline_path: str = "models/baseline_model.pkl",
    deep_path: str = "models/deep_model.h5",
    results_dir: str = "results",
    output_csv: str = "rvc_synthetic_evaluation.csv"
) -> pd.DataFrame:
    """
    Evaluates detector performance on the synthetic dataset generated by Applio RVC.
    """
    target_dir = Path(audio_dir).resolve()
    if not target_dir.is_dir():
        raise FileNotFoundError(f"Audio directory not found at: {target_dir}")

    meta_path = Path(metadata_file).resolve()
    metadata_df = None
    if meta_path.is_file():
        metadata_df = pd.read_csv(meta_path)
        print(f"[INFO] Loaded metadata with {len(metadata_df)} record(s) from: {meta_path.name}")

    # Gather audio files
    audio_files = sorted(list(target_dir.glob("*.wav")) + list(target_dir.glob("*.mp3")))
    if not audio_files:
        raise FileNotFoundError(f"No WAV/MP3 files found in: {target_dir}")

    print("=" * 80)
    print("      EVALUATING AUDIO DEEPFAKE DETECTORS ON RVC SYNTHETIC DATASET      ")
    print("=" * 80)
    print(f"Target Directory    : {target_dir}")
    print(f"Total Samples Found : {len(audio_files)}")
    print("Ground Truth Label  : FAKE / DEEPFAKE (1)")
    print("=" * 80)

    # Load Scaler
    scaler_file = Path(scaler_path).resolve()
    if not scaler_file.is_file():
        raise FileNotFoundError(f"Scaler not found at: {scaler_file}")
    scaler = joblib.load(scaler_file)
    print(f"[OK] Loaded Scaler from: {scaler_file.name}")

    # Load Baseline Model (SVM)
    baseline_file = Path(baseline_path).resolve()
    baseline_model = None
    if baseline_file.is_file():
        baseline_model = joblib.load(baseline_file)
        print(f"[OK] Loaded Baseline SVM from: {baseline_file.name}")

    # Load Deep Model (ResNeXt)
    deep_file = Path(deep_path).resolve()
    deep_model = None
    if deep_file.is_file():
        try:
            import tensorflow as tf
            class PatchedGlorot(tf.keras.initializers.GlorotUniform):
                def __init__(self, *args, **kwargs):
                    kwargs.pop("input_axes", None)
                    kwargs.pop("output_axes", None)
                    super().__init__(*args, **kwargs)

            deep_model = tf.keras.models.load_model(str(deep_file), custom_objects={"GlorotUniform": PatchedGlorot})
            print(f"[OK] Loaded ResNeXt Deep Model from: {deep_file.name}")
        except Exception as e_load:
            try:
                from src.train_deep_model import build_deepfake_detector_model
                deep_model = build_deepfake_detector_model()
                deep_model.load_weights(str(deep_file))
                print(f"[OK] Loaded ResNeXt Deep Model weights directly from: {deep_file.name}")
            except Exception as e_weights:
                print(f"[WARNING] Could not load ResNeXt deep model: {e_load} | fallback: {e_weights}")

    results_data = []

    for file_path in audio_files:
        # Match speaker_id and text from metadata if available
        speaker_id = "unknown"
        prompt_text = ""
        if metadata_df is not None:
            match = metadata_df[metadata_df["file"] == file_path.name]
            if not match.empty:
                speaker_id = match.iloc[0].get("speaker_id", "unknown")
                prompt_text = match.iloc[0].get("text", "")

        try:
            # 1. Standardized Preprocessing & 78-dim Feature Extraction
            feat = preprocess_and_extract(str(file_path)).reshape(1, -1)
            feat_scaled = scaler.transform(feat)

            record = {
                "file": file_path.name,
                "speaker_id": speaker_id,
                "ground_truth": "Fake (1)",
                "text": prompt_text
            }

            # 2. Evaluate Baseline SVM
            if baseline_model is not None:
                svm_pred = int(baseline_model.predict(feat_scaled)[0])
                if hasattr(baseline_model, "predict_proba"):
                    svm_prob_fake = float(baseline_model.predict_proba(feat_scaled)[0][1])
                else:
                    decision = float(baseline_model.decision_function(feat_scaled)[0])
                    svm_prob_fake = float(1 / (1 + np.exp(-decision)))

                record["svm_pred"] = "Fake" if svm_pred == 1 else "Real"
                record["svm_conf_fake_%"] = round(svm_prob_fake * 100, 2)
                record["svm_status"] = "DETECTED" if svm_pred == 1 else "EVADED (Misclassified)"

            # 3. Evaluate Deep ResNeXt CNN
            if deep_model is not None:
                X_2d = feat_scaled.reshape(1, 6, 13, 1)
                deep_prob_fake = float(deep_model.predict(X_2d, verbose=0)[0][0])
                deep_pred = int(deep_prob_fake >= 0.5)

                record["resnext_pred"] = "Fake" if deep_pred == 1 else "Real"
                record["resnext_conf_fake_%"] = round(deep_prob_fake * 100, 2)
                record["resnext_status"] = "DETECTED" if deep_pred == 1 else "EVADED (Misclassified)"

            results_data.append(record)

        except Exception as e:
            print(f"[ERROR] Evaluating '{file_path.name}': {e}")

    df_results = pd.DataFrame(results_data)

    # Print Summary Table
    print("\n" + "=" * 80)
    print("                           DETECTOR EVALUATION TABLE                           ")
    print("=" * 80)
    cols = ["file", "speaker_id"]
    if "svm_pred" in df_results.columns:
        cols.extend(["svm_pred", "svm_conf_fake_%", "svm_status"])
    if "resnext_pred" in df_results.columns:
        cols.extend(["resnext_pred", "resnext_conf_fake_%", "resnext_status"])

    print(df_results[cols].to_string(index=False))
    print("=" * 80)

    # Overall Detection Rates
    total = len(df_results)
    if total > 0:
        if "svm_pred" in df_results.columns:
            svm_correct = (df_results["svm_pred"] == "Fake").sum()
            print(f"Overall SVM Detection Rate     : {svm_correct}/{total} ({svm_correct/total*100:.1f}%)")
        if "resnext_pred" in df_results.columns:
            rn_correct = (df_results["resnext_pred"] == "Fake").sum()
            print(f"Overall ResNeXt Detection Rate : {rn_correct}/{total} ({rn_correct/total*100:.1f}%)")

        # Per-Speaker Breakdown
        if "speaker_id" in df_results.columns and df_results["speaker_id"].nunique() > 1:
            print("\n--- Per-Speaker Detection Breakdown ---")
            for spk, spk_df in df_results.groupby("speaker_id"):
                spk_total = len(spk_df)
                svm_c = (spk_df["svm_pred"] == "Fake").sum() if "svm_pred" in spk_df.columns else 0
                rn_c = (spk_df["resnext_pred"] == "Fake").sum() if "resnext_pred" in spk_df.columns else 0
                print(f"  [{spk}] ({spk_total} clips): SVM={svm_c}/{spk_total} ({svm_c/spk_total*100:.1f}%) | ResNeXt={rn_c}/{spk_total} ({rn_c/spk_total*100:.1f}%)")

    # Save CSV
    out_dir = Path(results_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    out_csv = out_dir / output_csv
    df_results.to_csv(out_csv, index=False)
    print("=" * 80)
    print(f"[OK] Evaluation results saved to: {out_csv}")
    print("=" * 80)

    return df_results


def main():
    parser = argparse.ArgumentParser(description="Evaluate deepfake detectors on synthetic RVC dataset.")
    parser.add_argument("--audio-dir", type=str, default="data/synthetic_rvc",
                        help="Path to folder containing synthetic audio files.")
    parser.add_argument("--metadata-file", type=str, default="data/synthetic_rvc/metadata.csv",
                        help="Path to metadata.csv.")
    parser.add_argument("--scaler-path", type=str, default="models/scaler.pkl",
                        help="Path to scaler.pkl.")
    parser.add_argument("--baseline-path", type=str, default="models/baseline_model.pkl",
                        help="Path to baseline_model.pkl.")
    parser.add_argument("--deep-path", type=str, default="models/deep_model.h5",
                        help="Path to deep_model.h5.")
    parser.add_argument("--results-dir", type=str, default="results",
                        help="Directory to save evaluation CSV.")
    parser.add_argument("--output-csv", type=str, default="rvc_synthetic_evaluation.csv",
                        help="Filename for results CSV.")

    args = parser.parse_args()

    evaluate_synthetic_dataset(
        audio_dir=args.audio_dir,
        metadata_file=args.metadata_file,
        scaler_path=args.scaler_path,
        baseline_path=args.baseline_path,
        deep_path=args.deep_path,
        results_dir=args.results_dir,
        output_csv=args.output_csv
    )


if __name__ == "__main__":
    main()
